#!/usr/bin/env python3
"""Build the game art that is drawn by code.

    python tools/art/build.py              # draw every game
    python tools/art/build.py man-eater    # draw one game
    python tools/art/build.py --check      # draw nothing; check the SVGs, manifests and galleries are current

Each game's drawing code is `games/<slug>/art/src/*.py` (files starting with `_` are helpers, loaded
by `artkit.sibling`). Every `@asset` there becomes `games/<slug>/art/<group>/<id>.svg`. The build also
writes `games/<slug>/art/art.json` (the manifest) and `games/<slug>/art/README.md` (a gallery).
Stdlib only. Exit 0 when clean, 1 when not.
"""
from __future__ import annotations

import importlib.util
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
import artkit  # noqa: E402

MAX_BYTES = 160_000
MAX_GAME_BYTES = 9_000_000
ID_RE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")
FORBIDDEN = re.compile(r"<script|<image|<foreignObject|href\s*=\s*\"(?!#)|url\((?!#)|@import", re.I)
FONTS = {"serif", "sans-serif", "monospace", "cursive", "fantasy"}
FONT_RE = re.compile(r'font-family="([^"]*)"')


def titles():
    out = {}
    for p in sorted((ROOT / "games").iterdir()):
        g = p / "data" / "game.json"
        if g.is_file():
            out[p.name] = json.loads(g.read_text(encoding="utf-8")).get("title", p.name)
    return out


def load(slug):
    src = ROOT / "games" / slug / "art" / "src"
    files = sorted(p for p in src.glob("*.py") if not p.name.startswith("_")) if src.is_dir() else []
    for p in files:
        spec = importlib.util.spec_from_file_location(f"art_{slug.replace('-', '_')}_{p.stem}", p)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
    return bool(files)


def draw(e) -> str:
    desc = " ".join((e["fn"].__doc__ or "").split())
    a = artkit.Art(e["game"], e["id"], e["title"], desc, e["w"], e["h"])
    e["fn"](a)
    return a.svg()


def check_svg(rel, s, problems):
    if len(s.encode("utf-8")) > MAX_BYTES:
        problems.append(f"{rel}: {len(s.encode('utf-8'))} bytes, over {MAX_BYTES}")
    if FORBIDDEN.search(s):
        problems.append(f"{rel}: holds a script, raster or external reference")
    for fam in FONT_RE.findall(s):
        bad = [x.strip() for x in fam.split(",") if x.strip() not in FONTS]
        if bad:
            problems.append(f"{rel}: font-family '{fam}' is not a generic family")
            break
    try:
        root = ET.fromstring(s)
    except ET.ParseError as ex:
        problems.append(f"{rel}: not well-formed XML ({ex})")
        return
    ns = "{http://www.w3.org/2000/svg}"
    if root.find(ns + "title") is None or not (root.findtext(ns + "desc") or "").strip():
        problems.append(f"{rel}: needs a title and a non-empty desc (the drawing function's docstring)")
    if len(list(root.iter())) < 8:
        problems.append(f"{rel}: almost empty ({len(list(root.iter()))} elements)")


def gallery(slug, title, entries) -> str:
    out = [f"# {title}: art drawn by code", "",
           f"{len(entries)} assets, generated by `python tools/art/build.py {slug}` from `art/src/`. Do not edit the",
           "SVGs by hand; change the code and rebuild.", ""]
    for g in artkit.GROUPS:
        es = [e for e in entries if e["group"] == g]
        if not es:
            continue
        out += [f"## {g} ({len(es)})", ""]
        for e in es:
            out.append(f'<img src="{g}/{e["id"]}.svg" alt="{e["title"]}" title="{e["title"]}" width="{min(260, e["w"])}">')
        out.append("")
    return "\n".join(out)


def main(argv):
    check = "--check" in argv
    only = [a for a in argv if not a.startswith("-")]
    names = titles()
    slugs = [s for s in names if not only or s in only]
    problems, total = [], 0
    for slug in slugs:
        art = ROOT / "games" / slug / "art"
        try:
            if not load(slug):
                continue
        except Exception as ex:  # a broken source file is a finding, not a crash
            problems.append(f"{slug}: art/src failed to load: {type(ex).__name__}: {ex}")
            continue
        entries = sorted((e for (g, _), e in artkit.REGISTRY.items() if g == slug),
                         key=lambda e: (artkit.GROUPS.index(e["group"]), e["id"]))
        size, wanted = 0, set()
        for e in entries:
            rel = f"games/{slug}/art/{e['group']}/{e['id']}.svg"
            if not ID_RE.match(e["id"]):
                problems.append(f"{rel}: id must be lower-case words joined by hyphens")
            try:
                svg = draw(e)
            except Exception as ex:
                problems.append(f"{rel}: drawing failed: {type(ex).__name__}: {ex}")
                continue
            out = ROOT / rel
            wanted.add(out)
            if check:
                if not out.is_file() or out.read_text(encoding="utf-8") != svg:
                    problems.append(f"{rel}: stale or missing; run build.py")
            else:
                out.parent.mkdir(parents=True, exist_ok=True)
                out.write_text(svg, encoding="utf-8")
            check_svg(rel, svg, problems)
            size += len(svg.encode("utf-8"))
        if size > MAX_GAME_BYTES:
            problems.append(f"{slug}: art is {size} bytes, over {MAX_GAME_BYTES}")
        for p in sorted(art.glob("*/*.svg")):
            if p not in wanted:
                if check:
                    problems.append(f"{p.relative_to(ROOT)}: no asset draws this file")
                else:
                    p.unlink()
        manifest = json.dumps({"game": slug, "count": len(entries), "assets": [
            {k: e[k] for k in ("id", "group", "title", "w", "h", "row")} for e in entries]}, indent=1) + "\n"
        gal = gallery(slug, names[slug], entries)
        for path, text in ((art / "art.json", manifest), (art / "README.md", gal)):
            if check:
                if not path.is_file() or path.read_text(encoding="utf-8") != text:
                    problems.append(f"{path.relative_to(ROOT)}: stale or missing; run build.py")
            else:
                path.write_text(text, encoding="utf-8")
        total += len(entries)
        print(f"     {slug}: {len(entries)} assets, {size // 1024} KB")
    for p in problems[:60]:
        print(p)
    if len(problems) > 60:
        print(f"... and {len(problems) - 60} more")
    print(f"ok   art ({total})" if not problems else f"FAIL art ({len(problems)} problems)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
